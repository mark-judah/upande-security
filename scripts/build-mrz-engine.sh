#!/bin/bash
# Bundle the MRZ engine (lib/mrz/engineWeb.ts + the recognizer weights) into
# lib/mrz/engineHtml.ts - the page the scan screen's hidden WebView loads.
# Re-run after changing anything in lib/mrz/ or lib/utils/mrz.ts, or after
# exporting new weights (mrz-scanner: uv run python -m export.to_ts ...).
set -euo pipefail
cd "$(dirname "$0")/.."
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
npx --yes esbuild@0.28.2 lib/mrz/engineWeb.ts --bundle --format=iife --minify --target=es2019 \
  --outfile="$tmp/engine.js" --log-level=warning
node -e '
const fs = require("fs");
const js = fs.readFileSync(process.argv[1], "utf8").replace(/<\/script/gi, "<\\/script");
const html = "<!doctype html><html><head><meta charset=\"utf-8\"></head><body><script>" + js + "</script></body></html>";
fs.writeFileSync(process.argv[2],
  "// Generated by scripts/build-mrz-engine.sh - do not edit.\n" +
  "// The MRZ engine page (lib/mrz/engineWeb.ts bundled with its weights).\n\n" +
  "export const ENGINE_HTML = " + JSON.stringify(html) + ";\n");
' "$tmp/engine.js" lib/mrz/engineHtml.ts
echo "wrote lib/mrz/engineHtml.ts ($(du -h lib/mrz/engineHtml.ts | cut -f1))"
